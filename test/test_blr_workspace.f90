!===============================================================================
! Validation du workspace reutilisable (BLR_WORKSPACE_T) : COMPRESS_BLOCK et
! FAST_RECOMPRESS (via SCHUR_UPDATE_BLR_BLOCK) doivent produire des resultats
! IDENTIQUES (aux arrondis machine pres) avec et sans workspace fourni --
! seule la gestion memoire change, jamais le resultat numerique.
!===============================================================================
PROGRAM TEST_BLR_WORKSPACE
  USE BLR_COMPRESS_MOD
  IMPLICIT NONE

  INTEGER, PARAMETER :: NTRIALS = 20
  INTEGER :: TRIAL, M, N, KW, MI, NJ
  REAL(WP), PARAMETER :: TOL = 1.0E-4_WP
  TYPE(BLR_WORKSPACE_T) :: WS
  LOGICAL :: ALL_OK
  REAL(WP) :: MAXERR

  ALL_OK = .TRUE.
  CALL SET_FIXED_SEED()
  CALL BLR_WORKSPACE_ALLOC(WS, 80)

  ! --- 1) COMPRESS_BLOCK : avec/sans WS, tailles variees <= MAXDIM ---
  MAXERR = 0.0_WP
  DO TRIAL = 1, NTRIALS
    M = 10 + MOD(TRIAL*7, 70)
    N = 10 + MOD(TRIAL*13, 70)
    CALL CHECK_COMPRESS(M, N, MAXERR)
  END DO
  WRITE(6,'(A,ES12.4)') ' COMPRESS_BLOCK  : erreur max (avec vs sans WS) = ', MAXERR
  IF (MAXERR .GT. 1.0E-6_WP) ALL_OK = .FALSE.

  ! --- 2) SCHUR_UPDATE_BLR_BLOCK (donc FAST_RECOMPRESS) : avec/sans WS ---
  MAXERR = 0.0_WP
  DO TRIAL = 1, NTRIALS
    MI = 10 + MOD(TRIAL*5, 60)
    NJ = 10 + MOD(TRIAL*11, 60)
    KW = 10 + MOD(TRIAL*3, 60)
    CALL CHECK_SCHUR(MI, NJ, KW, MAXERR)
  END DO
  WRITE(6,'(A,ES12.4)') ' SCHUR_UPDATE_BLR_BLOCK : erreur max (avec vs sans WS) = ', MAXERR
  IF (MAXERR .GT. 1.0E-6_WP) ALL_OK = .FALSE.

  CALL BLR_WORKSPACE_FREE(WS)

  IF (ALL_OK) THEN
    WRITE(6,*) '=== TOUS LES TESTS BLR_WORKSPACE : OK ==='
  ELSE
    WRITE(6,*) '=== TOUS LES TESTS BLR_WORKSPACE : ECHEC ==='
    STOP 1
  END IF

CONTAINS

  SUBROUTINE SET_FIXED_SEED()
    INTEGER, ALLOCATABLE :: SEED(:)
    INTEGER :: NSEED
    CALL RANDOM_SEED(SIZE=NSEED)
    ALLOCATE(SEED(NSEED))
    SEED = 123
    CALL RANDOM_SEED(PUT=SEED)
    DEALLOCATE(SEED)
  END SUBROUTINE SET_FIXED_SEED

  SUBROUTINE RANDOM_COMPLEX(M, N, X)
    INTEGER, INTENT(IN) :: M, N
    COMPLEX(WP), INTENT(OUT) :: X(M,N)
    REAL(WP), ALLOCATABLE :: RP(:,:), IP(:,:)
    ALLOCATE(RP(M,N), IP(M,N))
    CALL RANDOM_NUMBER(RP)
    CALL RANDOM_NUMBER(IP)
    X = CMPLX(RP-0.5_WP, IP-0.5_WP, KIND=WP)
    DEALLOCATE(RP, IP)
  END SUBROUTINE RANDOM_COMPLEX

  ! Bloc a rang numerique faible (rang 3) + un peu de bruit -- pour exercer
  ! a la fois le chemin basse-rang ET le chemin dense de COMPRESS_BLOCK
  ! selon TRIAL (bruit plus fort un cas sur trois).
  SUBROUTINE RANDOM_LOWRANK(M, N, TRIAL, X)
    INTEGER, INTENT(IN) :: M, N, TRIAL
    COMPLEX(WP), INTENT(OUT) :: X(M,N)
    COMPLEX(WP), ALLOCATABLE :: U(:,:), V(:,:), NOISE(:,:)
    INTEGER, PARAMETER :: R = 3
    REAL(WP) :: NOISE_LEVEL
    ALLOCATE(U(M,R), V(R,N), NOISE(M,N))
    CALL RANDOM_COMPLEX(M, R, U)
    CALL RANDOM_COMPLEX(R, N, V)
    CALL RANDOM_COMPLEX(M, N, NOISE)
    IF (MOD(TRIAL,3) .EQ. 0) THEN
      NOISE_LEVEL = 0.5_WP   ! force le chemin dense (pas assez compressible)
    ELSE
      NOISE_LEVEL = 1.0E-7_WP
    END IF
    X = MATMUL(U,V) + NOISE_LEVEL*NOISE
    DEALLOCATE(U, V, NOISE)
  END SUBROUTINE RANDOM_LOWRANK

  SUBROUTINE CHECK_COMPRESS(M, N, MAXERR)
    INTEGER, INTENT(IN) :: M, N
    REAL(WP), INTENT(INOUT) :: MAXERR
    COMPLEX(WP), ALLOCATABLE :: B(:,:), DENSE1(:,:), DENSE2(:,:)
    TYPE(BLR_BLOCK_T) :: BLK1, BLK2
    REAL(WP) :: ERR

    ALLOCATE(B(M,N), DENSE1(M,N), DENSE2(M,N))
    CALL RANDOM_LOWRANK(M, N, M+N, B)

    CALL COMPRESS_BLOCK(M, N, B, M, TOL, BLK1)           ! sans WS
    CALL COMPRESS_BLOCK(M, N, B, M, TOL, BLK2, WS)        ! avec WS

    IF (BLK1%IS_LOWRANK .NEQV. BLK2%IS_LOWRANK) THEN
      WRITE(6,'(A,I0,A,I0)') '  DIVERGENCE IS_LOWRANK a M=', M, ' N=', N
      MAXERR = HUGE(1.0_WP)
      RETURN
    END IF

    CALL EXPAND_BLOCK(BLK1, DENSE1, M)
    CALL EXPAND_BLOCK(BLK2, DENSE2, M)
    ERR = SQRT(SUM(ABS(DENSE1-DENSE2)**2)) / MAX(SQRT(SUM(ABS(DENSE1)**2)), TINY(1.0_WP))
    MAXERR = MAX(MAXERR, ERR)

    DEALLOCATE(B, DENSE1, DENSE2)
  END SUBROUTINE CHECK_COMPRESS

  SUBROUTINE CHECK_SCHUR(MI, NJ, KW, MAXERR)
    INTEGER, INTENT(IN) :: MI, NJ, KW
    REAL(WP), INTENT(INOUT) :: MAXERR
    COMPLEX(WP), ALLOCATABLE :: ARAW(:,:), LRAW(:,:), URAW(:,:), DENSE1(:,:), DENSE2(:,:)
    TYPE(BLR_BLOCK_T) :: ABLK1, ABLK2, LBLK, UBLK
    REAL(WP) :: ERR

    ALLOCATE(ARAW(MI,NJ), LRAW(MI,KW), URAW(KW,NJ), DENSE1(MI,NJ), DENSE2(MI,NJ))
    CALL RANDOM_LOWRANK(MI, NJ, MI+NJ+1, ARAW)
    CALL RANDOM_LOWRANK(MI, KW, MI+KW+2, LRAW)
    CALL RANDOM_LOWRANK(KW, NJ, KW+NJ+3, URAW)

    CALL COMPRESS_BLOCK(MI, NJ, ARAW, MI, TOL, ABLK1)
    CALL COMPRESS_BLOCK(MI, NJ, ARAW, MI, TOL, ABLK2)
    CALL COMPRESS_BLOCK(MI, KW, LRAW, MI, TOL, LBLK)
    CALL COMPRESS_BLOCK(KW, NJ, URAW, KW, TOL, UBLK)

    CALL SCHUR_UPDATE_BLR_BLOCK(ABLK1, MI, NJ, KW, LBLK, UBLK, TOL)         ! sans WS
    CALL SCHUR_UPDATE_BLR_BLOCK(ABLK2, MI, NJ, KW, LBLK, UBLK, TOL, WS)      ! avec WS

    IF (ABLK1%IS_LOWRANK .NEQV. ABLK2%IS_LOWRANK) THEN
      WRITE(6,'(A,I0,A,I0,A,I0)') '  DIVERGENCE IS_LOWRANK (Schur) a MI=', MI, ' NJ=', NJ, ' KW=', KW
      MAXERR = HUGE(1.0_WP)
      RETURN
    END IF

    CALL EXPAND_BLOCK(ABLK1, DENSE1, MI)
    CALL EXPAND_BLOCK(ABLK2, DENSE2, MI)
    ERR = SQRT(SUM(ABS(DENSE1-DENSE2)**2)) / MAX(SQRT(SUM(ABS(DENSE1)**2)), TINY(1.0_WP))
    MAXERR = MAX(MAXERR, ERR)

    DEALLOCATE(ARAW, LRAW, URAW, DENSE1, DENSE2)
  END SUBROUTINE CHECK_SCHUR

END PROGRAM TEST_BLR_WORKSPACE
